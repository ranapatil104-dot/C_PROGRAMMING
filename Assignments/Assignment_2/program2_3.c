#include<stdio.h>
#include<stdlib.h>

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  // Function Name : Display
// Description   : Accept one number from user if number is less than 10 then print "Hello" otherwise print "Demo"
// Input         : Integer
// Output        : String (Hello / Demo)
//  Author         :  Ranaranjit mahesh patil
//  Date           :  22/10/2026
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    if(iNo < 10)
    {
        printf("Hello");
    }
    else
    {
        printf("Demo");
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Of The Application
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number");
    scanf("%d", &iValue);

    Display(iValue);

    return EXIT_SUCCESS;
}