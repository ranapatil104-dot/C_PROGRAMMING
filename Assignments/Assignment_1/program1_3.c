#include <stdio.h>
#include<stdlib.h>

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name : Display
//  Description   : Program to print 5 to 1 numbers on screen
//  Input         : None
//  Output        : Integers (5 4 3 2 1)
//  Author        : Ranaranjit mahesh patil
//  Date          : 22/10/2026
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


void Display()
{
    int i = 0;
    i = 5;
    while(i >= 1)
    {
        printf("%d\t", i);
        i--;
    }
}

/////////////////////////////////////////////////////////////
//
//  Entry point Of The Application
//
////////////////////////////////////////////////////////////

int main()
{

    Display();

    return EXIT_SUCCESS;
}